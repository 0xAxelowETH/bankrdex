// Merges every supabase/migrations/*.sql file, in order, into supabase/all_migrations.sql.
// The output is ONE statement (a single DO block, each migration a nested block), so SQL runners
// that prepare one statement at a time can run it without "cannot insert multiple commands into
// a prepared statement". Every migration must itself be a single `do $migration$ ... $migration$;`.
// Usage: npm run db:merge
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const dir = join(process.cwd(), 'supabase', 'migrations');
const out = join(process.cwd(), 'supabase', 'all_migrations.sql');
const indent = (text) => text.split('\n').map((line) => (line.trim() ? `  ${line}` : '')).join('\n');

const files = readdirSync(dir).filter((f) => f.endsWith('.sql')).sort();
const blocks = files.map((file) => {
  const sql = readFileSync(join(dir, file), 'utf8').replace(/\r\n/g, '\n').trim();
  const match = sql.match(/^((?:--[^\n]*\n)*)do \$migration\$\n([\s\S]*)\n\$migration\$;$/);
  if (!match) throw new Error(`${file}: not a single "do $migration$ ... $migration$;" block`);
  const [, comments, body] = match;
  return indent(`-- ==== ${file}\n${comments}${body}`);
});

writeFileSync(
  out,
  `-- Generated by scripts/merge-migrations.mjs from supabase/migrations: do not edit by hand.\n` +
    `-- One DO block (one statement): safe for runners that reject multiple commands per statement.\n` +
    `do $all_migrations$\nbegin\n${blocks.join('\n\n')}\nend;\n$all_migrations$;\n`,
);
console.log(`Merged ${files.length} migrations into supabase/all_migrations.sql`);
